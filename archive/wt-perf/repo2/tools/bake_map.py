#!/usr/bin/env python3
"""bake_map.py NOR.img OUT.c [BUDGET] [EPISODE MAP]
Writes the hottest streams of one map block of DOOM.DAT as const data (data ROM, the ~90 KB that
/bin/doomd leaves unused) so their record reads never go to the disk: bakemap.c is linked into
/bin/doomd, bake_init() enables it only when the image's map entry has the same offset/size/CRC.
Streams are chosen by measured disk requests per byte (E1M1 attract demo)."""
import struct, sys
img = open(sys.argv[1], 'rb').read()
out = sys.argv[2]
budget = int(sys.argv[3]) if len(sys.argv) > 3 else 82000
ep, mp = (int(sys.argv[4]), int(sys.argv[5])) if len(sys.argv) > 5 else (1, 1)

def vol(base, name):
    bps, spc, res, nf, nroot, tot, _, fsz = struct.unpack_from('<HBHBHHBH', img, base + 11)
    root = base + (res + nf * fsz) * bps
    for i in range(nroot):
        e = img[root + i * 32:root + i * 32 + 32]
        if e[:11] == name:
            assert struct.unpack_from('<H', e, 26)[0] == 2, 'file not at cluster 2'
            return root + nroot * 32, struct.unpack_from('<I', e, 28)[0]
    raise SystemExit('no ' + name.decode())
d0, split = vol(0x100000, b'DOOM    DAT')
d1, _ = vol(0, b'DOOMX   DAT')
def logical(off, n):
    out = b''
    while n:
        if off < split:
            k = min(n, split - off); out += img[d0 + off:d0 + off + k]
        else:
            k = n; out += img[d1 + 64 + off - split:d1 + 64 + off - split + k]
        off += k; n -= k
    return out
k = 0
while True:
    e = logical(1792 + 32 * k, 32)
    off, size, crc, e_, m_ = struct.unpack_from('<IIIBB', e, 8)
    if e_ == ep and m_ == mp: break
    k += 1
hdr = logical(off, 512)
so = struct.unpack_from('<24I', hdr, 64); ss = struct.unpack_from('<24I', hdr, 160)
N = "NODES NODEBB SSECT SEGS LINES LINESIDES SIDES SECTORS SECEXTRA SECLINES TAGS BLOCKMAP GRID REJECT SNDADJ THINGS CELLTHINGS SECTHINGS ZCLIP TELEDEST SPECIALS MONSTERS TEXXLAT FLATXLAT".split()
def st(n): i = N.index(n); return off + so[i], ss[i]
ranges = []
lo = st('LINESIDES')[0]; hi = st('SECTORS')[0] + st('SECTORS')[1]   # LINESIDES, SIDES, SECTORS are contiguous
ranges.append((lo, hi - lo))
for n in ('NODES', 'SSECT', 'THINGS', 'SECTHINGS', 'ZCLIP'):
    ranges.append(st(n))
used = sum(l for _, l in ranges)
rest = (budget - used) & ~15
if rest > 0:
    lo, ln = st('LINES'); ranges.append((lo, min(rest, ln)))
ranges.sort()
data = b''.join(logical(lo, ln) + b'\0' * (-ln & 3) for lo, ln in ranges)
with open(out, 'w') as f:
    f.write('// generated by tools/bake_map.py from %s: map E%dM%d, %d ranges, %d bytes\n#include <stdint.h>\n' % (sys.argv[1], ep, mp, len(ranges), len(data)))
    f.write('const uint32_t bake_key[5] = {%d,%d,%d,%d,%d};\n' % (ep, mp, off, size, crc))
    f.write('const uint32_t bake_n = %d;\n' % len(ranges))
    pos = 0; rows = []
    for lo, ln in ranges:
        rows.append('{%d,%d,%d}' % (lo, ln, pos)); pos += (ln + 3) & ~3
    f.write('const uint32_t bake_rng[%d][3] = {%s};\n' % (len(ranges), ','.join(rows)))
    f.write('const uint32_t bake_data[%d] __attribute__((aligned(4))) = {\n' % (len(data) // 4))
    w = struct.unpack('<%dI' % (len(data) // 4), data)
    for i in range(0, len(w), 12): f.write(','.join('0x%x' % x for x in w[i:i + 12]) + ',\n')
    f.write('};\n')
print('baked', len(data), 'bytes in', len(ranges), 'ranges; map crc', hex(crc))
