base = {
 "comment": "QwenOS /bin/doomd RAM layout, generated by ports/doomdmc/mklayout.py",
 "ram_total": 32768, "stack": stack, "fixed_core": sy['__frame_start'],
 "plans": {"A": {"w": 8, "k": K, "textured": True, "frame_region": 9648} if w8only else {"w": 16, "k": K, "textured": True, "frame_region": 15208},
           "B": {"w": 8, "k": K, "textured": True, "frame_region": 9648},
           "C": {"w": 8, "k": K, "textured": True, "frame_region": 9648},
           "D": {"w": 8, "k": K, "textured": True, "frame_region": 9648}},
 "map_cache_lines": 4 * sets, "map_cache_bytes": 4 * sets * (line + 2) + sets, "flat_slot_bytes": 1028,
 "page_bytes": 60, "reserve_pages": 8, "transients": 24, "awake_min": 24, "awake_percent": 30,
 "level_fixed": {"sector_bytes": 1, "mutable_bytes": 10, "line_bits": 2, "special_bits": 1,
  "switch_bytes": 16, "button_bytes": 128, "tier_bits": 2, "sleep_bytes": 1, "monster_bits": 1,
  "zclip_bytes": 4, "blockmap_hash_bytes": 256, "sector_hash_bytes": 128, "light_bytes": 8,
  "mover_bytes": 20, "mover_max": 32, "platlist_bytes": 60, "drop_bytes": 16}}
json.dump(base, open(out, 'w'), indent=1)
print('layout: stack %d fixed_core %d caches %d -> arena(A) %d arena(B) %d' % (
    stack, sy['__frame_start'], base['map_cache_bytes'],
    32768 - stack - sy['__frame_start'] - 15208 - base['map_cache_bytes'] - K * 1028,
    32768 - stack - sy['__frame_start'] - 9648 - base['map_cache_bytes'] - K * 1028))
