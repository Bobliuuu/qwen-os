#!/usr/bin/env python3
"""RAM layout JSON for DMC100's converter (tools/conv/plan.py) from the built /bin/doomd ELF.
usage: mklayout.py doomd.elf OUT.json [rc_line rc_sets]      (rc geometry must match build.sh RC_DEFS)
The converter sizes each map's arena as ram_total - stack - fixed_core - frame region - caches, and
the engine places the arena at __ram_end - arena_bytes, so stack = the doomd stack reserve and
fixed_core = __frame_start (kernel core + engine .data/.bss, everything below the frame region).
Every plan has K = 1 flat slot (the flats that did not fit the data ROM are loaded into it) and is textured; B, C and D are the
same w = 8 plan (frame regions below 8368 B would overlap the front-end compose buffers)."""
import json, subprocess, sys
elf, out = sys.argv[1:3]
line, sets = (int(sys.argv[3]), int(sys.argv[4])) if len(sys.argv) > 4 else (16, 16)
w8only = len(sys.argv) > 5 and sys.argv[5] == 'w8'   # experiment: no w = 16 plan
import os
K = int(os.environ.get("QFLAT_SLOTS", 1))   # RAM flat slots for the flats that are not in data ROM
sy = {}
for l in subprocess.check_output(['readelf', '-sW', elf], text=True).splitlines():
    f = l.split()
    if len(f) >= 8 and f[0].rstrip(':').isdigit(): sy[f[-1]] = int(f[1], 16)
stack = 0x8000 - sy['__stack_limit']
