#!/usr/bin/env python3
"""Bake the most used floor/ceiling flats of the pack's maps into data ROM (QwenOS /bin/doomd).
usage: mkflatrom.py DMC_CHECKOUT PACK_DIR OUT.c        (env QFLATS_MAX = number of flats, default 88)
Flats are 32x32 texels (1024 B) in the pack's FLATS section. Sector pic numbers are map-local; they are
translated through the map's FLATXLAT stream (what P_MapFlat does) to global flat ids. Animation cycles
that a map uses are baked whole, then the flats with the most sector references (every map weighs the same).
The engine (dmc-ram.patch, fetch.c) returns a pointer into q_flat_rom for those: no cache RAM, no flat disk
read, pixel-identical to the disk path. The remaining flats (about 3 % of the sector references in E1) go
through the single RAM flat slot."""
import sys
dmc, pack, out = sys.argv[1:4]
sys.path.insert(0, dmc + '/tools')
from conv import format as F, reader as R
img = R.Image(pack)
import collections, os
# usage per flat: sector floor/ceiling references, each map weighted equally (pic numbers are
# map-local; the map's FLATXLAT stream maps them to global flat ids, P_MapFlat)
score = collections.Counter(); every = set()
# QFLAT_MAPS=E1M1[,E1M2..]: bake only the flats of these maps (E1M1-focused build: ~10 flats instead of 88)
only = [m for m in os.environ.get('QFLAT_MAPS', '').split(',') if m]
for e in img.maps:
    if only and e['name'] not in only: continue
    mb = img.map(e['name'])
    xlat = mb.u16s('FLATXLAT'); c = collections.Counter()
    for s in mb.records('SECTORS', F.SECTOR):
        for pic in (s['floorpic'], s['ceilingpic']):
            if xlat[pic] != F.NONE16: c[xlat[pic]] += 1
    for f, n in c.items(): score[f] += n / sum(c.values())
    every |= set(c)
anim = set()
an, _ = img.section('ANIMS')
for i in range(len(an) // F.ANIM.size):
    a = F.ANIM.unpack(an, i * F.ANIM.size)
    if a['kind'] == F.ANIM_FLAT and any(f in every for f in range(a['first'], a['last'] + 1)):
        anim.update(range(a['first'], a['last'] + 1))   # cycles are baked whole (or not at all)
fl, fe = img.section('FLATS')
count = fe['flags']
assert F.finale_flat_off(count) <= len(fl), (count, len(fl))
# the data ROM holds what the engine's rodata leaves free: bake animation cycles first, then the most used
# flats up to QFLATS_MAX (default 88 = 90112 B; 0 bakes nothing, a debug setting)
limit = int(os.environ.get('QFLATS_MAX', 88))
order = sorted(anim) + [f for f, _ in score.most_common() if f not in anim]
used = sorted(set(order[:limit]))
covered = sum(1 for f in every if f in used)
idx = {f: k for k, f in enumerate(used)}
L = ['// Generated by ports/doomdmc/mkflatrom.py: %d of %d flats in data ROM (%d B)' % (len(used), count, len(used) * 1024),
     '#include <stdint.h>',
     'const uint16_t q_flat_idx[%d] = {' % count]
L += ['    %s,' % (idx[f] if f in idx else '0xFFFF') for f in range(count)]
L += ['};', 'const uint8_t q_flat_rom[%d][1024] __attribute__((aligned(4))) = {' % len(used)]
for f in used:
    d = fl[f * 1024:(f + 1) * 1024]
    L.append('{' + ','.join(str(b) for b in d) + '},')
L.append('};')
open(out, 'w').write('\n'.join(L) + '\n')
print('flatrom: %d of %d flats baked (%d B); %d of %d flats the maps use' % (len(used), count, len(used) * 1024, covered, len(every)))
